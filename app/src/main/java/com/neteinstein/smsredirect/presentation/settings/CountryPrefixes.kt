/**
 * An ISO 3166-1 alpha-2 country/territory code paired with its international calling code,
 * e.g. isoCode = "PT", dialCode = "351" represents Portugal's +351.
 */
data class CountryPrefix(
    val isoCode: String,
    val dialCode: String,
) {
    /** The dial code formatted as a "+"-prefixed value, e.g. "+351". */
    val prefix: String get() = "+$dialCode"

    /**
     * The country/territory name localized for [locale]. Resolved via [Locale] instead of a
     * translated string resource so every language the app supports gets a correct name for free.
     */
    fun displayName(locale: Locale): String =
        Locale
            .Builder()
            .setRegion(isoCode)
            .build()
            .getDisplayCountry(locale)
}

