/**
 * Builds the (dial code, label) options for the default-prefix dropdown, sorted alphabetically
 * by each country's name as localized for [locale].
 */
fun countryPrefixOptions(locale: Locale): List<Pair<String, String>> {
    val collator = Collator.getInstance(locale)
    return allCountryPrefixes
        .map { it.prefix to "${it.displayName(locale)} (${it.prefix})" }
        .sortedWith { a, b -> collator.compare(a.second, b.second) }
}
